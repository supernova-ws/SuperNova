  public function driver_disconnect() {
    if (is_object($this->pdo)) {
      $this->pdo       = null;
      $this->connected = false;
      unset($this->pdo);
    }

    return true;
  }

  public function db_error() {
//    return mysqli_error($this->link);
    return $this->pdo->errorInfo()[2] ?? null;
